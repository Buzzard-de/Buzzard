export function translateTurkishName(name) {
  if (trDe[name]) return trDe[name];

  return name
    .split(/\s*&\s*/)
    .map((part) =>
      part
        .trim()
        .split(/\s+/)
        .map((word) => trWordDe[word] ?? word)
        .join(" ")
    )
    .join(" & ");
}

export function germanCategoryName(node) {
  return mainDe[node.id] ?? translateTurkishName(node.name);
}

export function slugifyGerman(text) {
  return text
    .toLowerCase()
    .replace(/ä/g, "ae")
    .replace(/ö/g, "oe")
    .replace(/ü/g, "ue")
    .replace(/ß/g, "ss")
    .replace(/&/g, " und ")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export function germanCategorySlug(node, germanName) {
  if (mainSlugDe[node.id]) return mainSlugDe[node.id];
  return slugifyGerman(germanName);
}
