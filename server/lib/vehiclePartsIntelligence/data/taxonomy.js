function build() {
  const categories = [];
  for (const [slug, de, en, classes] of families) {
    const parentId = `vpe-cat-${slug}`;
    categories.push(n(parentId, null, slug, deen(de, en), classes, ["assembly"]));
    for (const [leaf, lde, len] of leaves[slug] || []) {
      categories.push(n(`vpe-cat-${leaf}`, parentId, leaf, deen(lde, len), classes, ["component"]));
    }
  }
  return categories;
}

